#!/usr/bin/env node
/**
 * Writes src/language-data.ts from CLDR (Unicode-3.0), installed as the pinned `cldr-misc-full`
 * devDependency, so what Reelsaw knows about a language's writing is Unicode's and not typed here:
 *   - `letters`: the main exemplar characters (the letters and marks the language is written with);
 *   - `terminals`: the language's punctuation that ends a sentence (its exemplar punctuation that
 *     Unicode marks Sentence_Terminal: "." "?" "!" for English, "।" for Hindi, "。" for Japanese);
 *   - `rtl`: the layout's character order is right-to-left.
 * One entry per CLDR locale that is a bare language ("hi", not "hi-Latn" or "en-GB").
 * `--check` fails when the file differs from what the installed CLDR gives (CI: `pnpm languages:check`).
 * To take a newer CLDR, bump `cldr-misc-full` in packages/shared/package.json and run this script.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ROOT = path.dirname(require.resolve("cldr-misc-full/package.json"));
const VERSION = JSON.parse(readFileSync(path.join(ROOT, "package.json"), "utf8")).version;
const OUT = fileURLToPath(new URL("../src/language-data.ts", import.meta.url));

/** Members of a CLDR UnicodeSet ("[a-z {ch} \\u200C ゝヽ]") as code points; strings ({ch}) give theirs. */
function members(set) {
  const out = [];
  const body = set.replace(/^\[|\]$/g, "");
  const cps = [...body];
  const read = (i) => {
    // one (possibly escaped) character at i → [codePoint, next index]
    if (cps[i] !== "\\") return [cps[i].codePointAt(0), i + 1];
    const n = cps[i + 1];
    if (n === "u") return [Number.parseInt(cps.slice(i + 2, i + 6).join(""), 16), i + 6];
    if (n === "x" && cps[i + 2] === "{") {
      const end = cps.indexOf("}", i);
      return [Number.parseInt(cps.slice(i + 3, end).join(""), 16), end + 1];
    }
    return [n.codePointAt(0), i + 2];
  };
  for (let i = 0; i < cps.length; ) {
    const c = cps[i];
    if (/\s/.test(c)) {
      i++;
    } else if (c === "{") {
      const end = cps.indexOf("}", i);
      for (const s of cps.slice(i + 1, end)) out.push(s.codePointAt(0));
      i = end + 1;
    } else {
      const [cp, next] = read(i);
      if (cps[next] === "-" && next + 1 < cps.length) {
        const [to, after] = read(next + 1);
        for (let x = cp; x <= to; x++) out.push(x);
        i = after;
      } else {
        out.push(cp);
        i = next;
      }
    }
  }
  return out;
}

/** Format controls (ZWJ, ZWNJ) shape the letters around them but are not drawn: no glyph to check. */
const drawn = (cp) => !/\p{Cf}/u.test(String.fromCodePoint(cp));
const str = (cps) => [...new Set(cps.filter(drawn))].map((cp) => String.fromCodePoint(cp)).join("");

const entries = [];
for (const code of readdirSync(path.join(ROOT, "main")).sort()) {
  if (code.includes("-") || code === "root" || code === "und") continue;
  const chars = JSON.parse(readFileSync(path.join(ROOT, "main", code, "characters.json"), "utf8")).main[code].characters;
  const layout = JSON.parse(readFileSync(path.join(ROOT, "main", code, "layout.json"), "utf8")).main[code].layout;
  const letters = str(members(chars.exemplarCharacters ?? "[]"));
  if (!letters) continue;
  const terminals = str(members(chars.punctuation ?? "[]").filter((cp) => /\p{Sentence_Terminal}/u.test(String.fromCodePoint(cp))));
  const rtl = layout?.orientation?.characterOrder === "right-to-left";
  entries.push(`  ${JSON.stringify(code)}: { letters: ${JSON.stringify(letters)}, terminals: ${JSON.stringify(terminals)}${rtl ? ", rtl: true" : ""} },`);
}
if (entries.length < 150) throw new Error(`only ${entries.length} languages read from cldr-misc-full ${VERSION}; did its layout change?`);

const text = `// Generated by packages/shared/scripts/language-data.mjs from cldr-misc-full@${VERSION} (Unicode-3.0).
// Do not edit: bump cldr-misc-full in packages/shared/package.json and run the script again.

/** Per language (a bare CLDR locale): the letters it is written with, its sentence-ending punctuation, right-to-left. */
// biome-ignore format: one generated table, one language per line
export const LANGUAGE_DATA: Record<string, { letters: string; terminals: string; rtl?: true }> = {
${entries.join("\n")}
};
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== text) {
    console.error(`src/language-data.ts is not what cldr-misc-full@${VERSION} gives: run node packages/shared/scripts/language-data.mjs`);
    process.exit(1);
  }
  console.log(`language-data.ts matches cldr-misc-full@${VERSION} (${entries.length} languages)`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${entries.length} languages, ${Buffer.byteLength(text)} bytes)`);
}
