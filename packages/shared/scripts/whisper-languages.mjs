#!/usr/bin/env node
/**
 * Writes src/whisper-languages.ts from Whisper's own language table (openai/whisper, MIT), so the
 * list is the model's and not one typed here. `--check` fails when the file differs from what the
 * pinned commit gives (CI: `pnpm languages:check`). To take a newer Whisper, change WHISPER_COMMIT
 * and run `node packages/shared/scripts/whisper-languages.mjs`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const WHISPER_COMMIT = "86098128c0b4f24f0e2aa2994de830614b474227";
const SOURCE = `https://raw.githubusercontent.com/openai/whisper/${WHISPER_COMMIT}/whisper/tokenizer.py`;
const OUT = fileURLToPath(new URL("../src/whisper-languages.ts", import.meta.url));

const res = await fetch(SOURCE, { signal: AbortSignal.timeout(30_000) });
if (!res.ok) throw new Error(`${SOURCE} returned HTTP ${res.status}`);
const py = await res.text();
const table = py.match(/^LANGUAGES = \{\n([\s\S]*?)\n\}/m)?.[1];
if (!table) throw new Error(`no LANGUAGES table in ${SOURCE}`);
const codes = [...table.matchAll(/^\s*"([a-z]+)":\s*"[^"]+",?$/gm)].map((m) => m[1]);
if (codes.length < 90) throw new Error(`only ${codes.length} languages parsed from ${SOURCE}; did the table's format change?`);

const rows = [];
const quoted = codes.map((c) => `"${c}"`);
for (let i = 0; i < codes.length; i += 20) rows.push(`  ${quoted.slice(i, i + 20).join(", ")},`);
const text = `// Generated by packages/shared/scripts/whisper-languages.mjs from openai/whisper@${WHISPER_COMMIT.slice(0, 7)} (MIT),
// whisper/tokenizer.py LANGUAGES. Do not edit: change WHISPER_COMMIT in the script and run it again.
// biome-ignore format: one code list, not one code per line
export const WHISPER_LANGUAGES = [
${rows.join("\n")}
] as const;
`;

if (process.argv.includes("--check")) {
  const now = readFileSync(OUT, "utf8");
  if (now !== text) {
    console.error(`${OUT} is not what openai/whisper@${WHISPER_COMMIT.slice(0, 7)} gives: run node packages/shared/scripts/whisper-languages.mjs`);
    process.exit(1);
  }
  console.log(`whisper-languages.ts matches openai/whisper@${WHISPER_COMMIT.slice(0, 7)} (${codes.length} languages)`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${codes.length} languages)`);
}
