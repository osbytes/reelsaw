#!/usr/bin/env node
/**
 * Writes src/whisper-languages.ts from Whisper's own language table (openai/whisper, MIT), so the
 * list is the model's and not one typed here. `--check` fails when the file differs from what the
 * pinned commit gives (CI: `pnpm languages:check`). To take a newer Whisper, change WHISPER_COMMIT
 * and run `node packages/shared/scripts/whisper-languages.mjs`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const WHISPER_COMMIT = "86098128c0b4f24f0e2aa2994de830614b474227";
const SOURCE = `https://raw.githubusercontent.com/openai/whisper/${WHISPER_COMMIT}/whisper/tokenizer.py`;
const OUT = fileURLToPath(new URL("../src/whisper-languages.ts", import.meta.url));

/** GitHub's raw host fails now and then; a check in CI should not fail with it. */
async function download() {
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(SOURCE, { signal: AbortSignal.timeout(30_000) });
      if (res.ok) return await res.text();
      if (res.status < 500 && res.status !== 429) throw new Error(`${SOURCE} returned HTTP ${res.status}`);
      if (attempt === 3) throw new Error(`${SOURCE} returned HTTP ${res.status}`);
    } catch (err) {
      if (attempt === 3 || /returned HTTP 4/.test(err.message)) throw err;
    }
    await new Promise((r) => setTimeout(r, attempt * 5_000));
  }
}

const py = await download();
const table = (name) => {
  const body = py.match(new RegExp(`^${name} = \\{\\n([\\s\\S]*?)\\n\\}`, "m"))?.[1];
  if (!body) throw new Error(`no ${name} table in ${SOURCE}`);
  return [...body.matchAll(/^\s*"([^"]+)":\s*"([^"]+)",?$/gm)].map((m) => [m[1], m[2]]);
};
// LANGUAGES is code → name; TO_LANGUAGE_CODE adds other names people use ("burmese", "mandarin") → code
const languages = table("LANGUAGES");
const names = [...languages.map(([code, name]) => [name, code]), ...table("TO_LANGUAGE_CODE")];
const codes = languages.map(([code]) => code);
if (codes.length < 90) throw new Error(`only ${codes.length} languages parsed from ${SOURCE}; did the table's format change?`);

const lines = (items, perLine) => {
  const out = [];
  for (let i = 0; i < items.length; i += perLine) out.push(`  ${items.slice(i, i + perLine).join(", ")},`);
  return out.join("\n");
};
const text = `// Generated by packages/shared/scripts/whisper-languages.mjs from openai/whisper@${WHISPER_COMMIT.slice(0, 7)} (MIT),
// whisper/tokenizer.py. Do not edit: change WHISPER_COMMIT in the script and run it again.

/** LANGUAGES: the codes Whisper takes, in its order (its own spellings: "jw" is Javanese). */
// biome-ignore format: one code list, not one code per line
export const WHISPER_LANGUAGES = [
${lines(
  codes.map((c) => `"${c}"`),
  20,
)}
] as const;

/** TO_LANGUAGE_CODE: the English names Whisper reports and takes ("bengali", "myanmar", "mandarin") → its code. */
// biome-ignore format: one table, not one entry per line
export const WHISPER_LANGUAGE_NAMES: Record<string, string> = {
${lines(
  names.map(([n, c]) => `"${n}": "${c}"`),
  6,
)}
};
`;

if (process.argv.includes("--check")) {
  const now = readFileSync(OUT, "utf8");
  if (now !== text) {
    console.error(`${OUT} is not what openai/whisper@${WHISPER_COMMIT.slice(0, 7)} gives: run node packages/shared/scripts/whisper-languages.mjs`);
    process.exit(1);
  }
  console.log(`whisper-languages.ts matches openai/whisper@${WHISPER_COMMIT.slice(0, 7)} (${codes.length} languages)`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${codes.length} languages)`);
}
